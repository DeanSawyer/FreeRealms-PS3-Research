#!/usr/bin/env python3
"""Write the C# copy of the character-creator mapping tables (src/ps3/Sanctuary.Ps3/Gateway/CharacterMappings.g.cs).

bootstrap/character_mappings.py is the source (Sanctuary's Resources/CharacterCreate/*Mappings.txt); the C# port reads the same
tables from the generated file so both servers send the same head, hair, face paint and body-option names.

    python tools/gen_character_mappings.py            # rewrite the generated file
    python tools/gen_character_mappings.py --check    # exit 1 if the committed file is out of date (used by CI)

Standard library only.
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "bootstrap"))

import character_mappings as cm  # noqa: E402

OUT = os.path.join(ROOT, "src", "ps3", "Sanctuary.Ps3", "Gateway", "CharacterMappings.g.cs")
TABLES = [("Heads", cm.HEADS), ("Hairs", cm.HAIRS), ("SkinTones", cm.SKIN_TONES), ("FacePaints", cm.FACE_PAINTS),
          ("ModelCustomizations", cm.MODEL_CUSTOMIZATIONS)]


def cs_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate():
    lines = [
        "// <auto-generated>",
        "// Written by tools/gen_character_mappings.py from bootstrap/character_mappings.py (Sanctuary's",
        "// Resources/CharacterCreate/*Mappings.txt). Do not edit by hand; run the script instead.",
        "// </auto-generated>",
        "",
        "using System.Collections.Generic;",
        "",
        "namespace Sanctuary.Ps3.Gateway;",
        "",
        "/// <summary>Character-creator choice numbers and the asset names the client draws for them.</summary>",
        "public static partial class CharacterMappings",
        "{",
    ]
    for name, table in TABLES:
        lines.append("    public static readonly IReadOnlyDictionary<int, string> %s = new Dictionary<int, string>" % name)
        lines.append("    {")
        for key in sorted(table):
            lines.append("        [%d] = %s," % (key, cs_string(table[key])))
        lines.append("    };")
        lines.append("")
    lines[-1] = "}"
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed file differs")
    args = ap.parse_args()
    text = generate()
    if args.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("%s is out of date; run python tools/gen_character_mappings.py" % os.path.relpath(OUT, ROOT))
            return 1
        print("character mappings are up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d bytes)" % (os.path.relpath(OUT, ROOT), len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
